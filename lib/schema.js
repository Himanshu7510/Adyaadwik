// Group long forms into sections in the admin
const GROUPS = {
  'Price & size': ['price', 'priceLabel', 'area', 'areaUnit', 'bedrooms', 'bathrooms', 'parking', 'floor', 'facing', 'furnishing', 'builtUpArea', 'units', 'progress', 'year', 'client'],
  'Location': ['city', 'locality', 'address', 'mapEmbed', 'location', 'reraNo'],
  'Photos & files': ['cover', 'gallery', 'video', 'brochure'],
  'Description': ['summary', 'description', 'amenities', 'highlights', 'excerpt', 'body', 'tags', 'points'],
  'Visibility': ['featured', 'published'],
};
for (const key of ['properties', 'projects', 'posts', 'services']) {
  for (const f of collections[key].fields) {
    if (f.group) continue;
    const g = Object.entries(GROUPS).find(([, names]) => names.includes(f.name));
    if (g && !(key === 'posts' && g[0] === 'Price & size')) f.group = g[0];
  }
}
